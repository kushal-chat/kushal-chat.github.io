#!/usr/bin/env node
// Static blog builder. No dependencies. Requires Node 18+.
//
//   node build.mjs                 build everything from posts/*.md
//   node build.mjs --watch         rebuild whenever posts/ or templates/ change
//   node build.mjs new "My title"   scaffold a new post
//   node build.mjs add-place "Name, Region" <lat> <lng> "Description" [link]   add a map pin
//
// Content lives in data/: places.json (map), projects.json, papers.json. See README.md.
//
// Each post is posts/<anything>.md with front matter:
//   ---
//   title: My title
//   date: 2026-11-23          (YYYY-MM-DD or just YYYY-MM; optional, falls back to a date filename prefix)
//   summary: One-line description shown in lists.
//   draft: true               (optional; skips the post)
//   ---
// Markdown supports headings, lists (nested), tables, quotes, code fences, images, links,
// $inline$ and $$display$$ math (KaTeX), raw HTML, and <div data-viz="name"></div> embeds.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(fileURLToPath(import.meta.url));
const P = (...a) => path.join(ROOT, ...a);
const MARK = '<!-- generated by build.mjs -->';
const MONTHS = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec'];
const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const slugify = s => s.toLowerCase().replace(/<[^>]+>/g, '').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

/* ------------------------------ markdown ------------------------------ */

function markdown(src) {
  const stash = [];
  const blocks = new Set();
  const put = (html, block = false) => {
    stash.push(html);
    if (block) blocks.add(stash.length - 1);
    return `\u0000${stash.length - 1}\u0000`;
  };
  let hasMath = false;

  src = src.replace(/\\\$/g, () => put('$'));                                   // \$ -> literal dollar
  src = src.replace(/^```(\S*)[^\n]*\n([\s\S]*?)^```[ \t]*$/gm, (_, lang, code) =>
    put(`<pre><code${lang ? ` class="language-${lang}"` : ''}>${esc(code.replace(/\n$/, ''))}</code></pre>`, true));
  src = src.replace(/`([^`\n]+)`/g, (_, c) => put(`<code>${esc(c)}</code>`));
  src = src.replace(/\$\$([\s\S]+?)\$\$/g, (_, m) => { hasMath = true; return put(`$$${esc(m)}$$`); });
  src = src.replace(/\$([^$\n]+?)\$/g, (_, m) => { hasMath = true; return put(`$${esc(m)}$`); });

  const inline = s => s
    .replace(/!\[([^\]]*)\]\(((?:[^()\s]|\([^()\s]*\))+)(?:\s+"([^"]*)")?\)/g, '<img src="$2" alt="$1" loading="lazy">')
    .replace(/\[([^\]]+)\]\(((?:[^()\s]|\([^()\s]*\))+)\)/g, '<a href="$2">$1</a>')
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/(^|[^*\w])\*([^*\n]+)\*(?!\w)/g, '$1<em>$2</em>')
    .replace(/(^|[^\w])_([^_\n]+)_(?!\w)/g, '$1<em>$2</em>');

  const listItem = /^(\s*)([-*+]|\d+[.)])\s+(.*)$/;
  const lines = src.split('\n');
  const out = [];
  let i = 0;

  while (i < lines.length) {
    const line = lines[i];
    if (!line.trim()) { i++; continue; }

    const tok = line.trim().match(/^\u0000(\d+)\u0000$/);
    if (tok && blocks.has(+tok[1])) { out.push(line.trim()); i++; continue; }

    if (/^\s*</.test(line)) {                                                       // raw HTML block
      const buf = [];
      while (i < lines.length && lines[i].trim()) buf.push(lines[i++]);
      out.push(buf.join('\n'));
      continue;
    }

    let m;
    if ((m = line.match(/^(#{1,4})\s+(.*)$/))) {                                    // heading
      const text = inline(m[2].trim());
      out.push(`<h${m[1].length} id="${slugify(m[2].replace(/\u0000\d+\u0000/g, '')) || 'h' + i}">${text}</h${m[1].length}>`);
      i++; continue;
    }
    if (/^(-{3,}|\*{3,})\s*$/.test(line)) { out.push('<hr>'); i++; continue; }

    if (/^>/.test(line)) {                                                          // blockquote
      const buf = [];
      while (i < lines.length && /^>/.test(lines[i])) buf.push(lines[i++].replace(/^>\s?/, ''));
      out.push(`<blockquote>${buf.map(l => inline(l)).join(' ')}</blockquote>`);
      continue;
    }

    if (listItem.test(line)) {                                                      // list (nested)
      const buf = [];
      while (i < lines.length && lines[i].trim() && (listItem.test(lines[i]) || /^\s/.test(lines[i]))) buf.push(lines[i++]);
      const items = [];
      for (const l of buf) {
        const mm = l.match(listItem);
        if (mm) items.push({ ind: mm[1].replace(/\t/g, '  ').length, ord: /\d/.test(mm[2]), text: mm[3] });
        else if (items.length) items[items.length - 1].text += ' ' + l.trim();
      }
      let pos = 0;
      const render = ind => {
        const ord = items[pos].ord;
        let html = '';
        while (pos < items.length && items[pos].ind >= ind) {
          const it = items[pos++];
          let inner = inline(it.text);
          if (pos < items.length && items[pos].ind > it.ind) inner += render(items[pos].ind);
          html += `<li>${inner}</li>`;
        }
        return ord ? `<ol>${html}</ol>` : `<ul>${html}</ul>`;
      };
      out.push(render(items[0].ind));
      continue;
    }

    if (line.includes('|') && i + 1 < lines.length && /^\s*\|?[\s:|-]+\|?\s*$/.test(lines[i + 1]) && lines[i + 1].includes('-')) { // table
      const cells = l => l.trim().replace(/^\||\|$/g, '').split('|').map(c => inline(c.trim()));
      const head = cells(line);
      i += 2;
      const rows = [];
      while (i < lines.length && lines[i].includes('|') && lines[i].trim()) rows.push(cells(lines[i++]));
      out.push(`<table><thead><tr>${head.map(c => `<th>${c}</th>`).join('')}</tr></thead><tbody>` +
        rows.map(r => `<tr>${r.map(c => `<td>${c}</td>`).join('')}</tr>`).join('') + '</tbody></table>');
      continue;
    }

    const buf = [];                                                                  // paragraph
    while (i < lines.length && lines[i].trim() && !/^(#{1,4}\s|>|\s*<|```)/.test(lines[i]) && !(buf.length && listItem.test(lines[i]))) buf.push(lines[i++].trim());
    out.push(`<p>${inline(buf.join(' '))}</p>`);
  }

  const html = out.join('\n').replace(/\u0000(\d+)\u0000/g, (_, n) => stash[+n]);
  return { html, hasMath };
}

/* ------------------------------ posts ------------------------------ */

function parsePost(file) {
  const raw = fs.readFileSync(P('posts', file), 'utf8').replace(/\r\n/g, '\n');
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?([\s\S]*)$/);
  const meta = {};
  let body = raw;
  if (m) {
    body = m[2];
    for (const l of m[1].split('\n')) {
      const kv = l.match(/^([A-Za-z_]+):\s*(.*)$/);
      if (kv) meta[kv[1].toLowerCase()] = kv[2].trim().replace(/^["']|["']$/g, '');
    }
  }
  const base = file.replace(/\.md$/, '');
  const dm = base.match(/^(\d{4}-\d{2}(?:-\d{2})?)-(.+)$/);
  const slug = slugify(dm ? dm[2] : base);
  const date = meta.date || (dm && dm[1]) || new Date().toISOString().slice(0, 10);
  const { html, hasMath } = markdown(body);
  const words = body.replace(/\$[^$]*\$|<[^>]+>/g, ' ').split(/\s+/).filter(Boolean).length;
  return {
    slug, date, html, hasMath,
    title: meta.title || slug,
    summary: meta.summary || '',
    draft: /^(true|yes)$/i.test(meta.draft || ''),
    minutes: Math.max(1, Math.round(words / 200)),
    hasViz: /data-viz=/.test(body),
  };
}

const fmtLong = d => { const [y, m, dd] = d.split('-').map(Number); return dd ? `${MONTHS[m - 1]} ${dd}, ${y}` : `${MONTHS[m - 1]} ${y}`; };
const fmtShort = d => { const [y, m] = d.split('-').map(Number); return `${MONTHS[m - 1]} ${y}`; };

const KATEX = `
  <link rel="stylesheet" href="https://cdn.jsdelivr.net/npm/katex@0.16.11/dist/katex.min.css">
  <script defer src="https://cdn.jsdelivr.net/npm/katex@0.16.11/dist/katex.min.js"></script>
  <script defer src="https://cdn.jsdelivr.net/npm/katex@0.16.11/dist/contrib/auto-render.min.js"
    onload="renderMathInElement(document.querySelector('.post-body'),{delimiters:[{left:'$$',right:'$$',display:true},{left:'$',right:'$',display:false}]})"></script>`;

const fill = (tpl, vars) => Object.entries(vars).reduce((s, [k, v]) => s.split(`{{${k}}}`).join(v), tpl);

const readJSON = (rel, fallback) => fs.existsSync(P(rel)) ? JSON.parse(fs.readFileSync(P(rel), 'utf8')) : fallback;
const writeJSON = (rel, obj) => fs.writeFileSync(P(rel), JSON.stringify(obj, null, 2) + '\n');

// Generic card renderer for projects.json / papers.json: { title, url?, meta?, description?, links?: [{label, url}] }
const entryHTML = e => `<div class="entry">
  <h3>${e.url ? `<a href="${esc(e.url)}">${esc(e.title)}</a>` : esc(e.title)}</h3>${e.meta ? `\n  <p class="meta">${esc(e.meta)}</p>` : ''}${e.description ? `\n  <p>${esc(e.description)}</p>` : ''}${(e.links || []).length ? `\n  <p class="links">${e.links.map(l => `<a href="${esc(l.url)}">${esc(l.label)}</a>`).join('')}</p>` : ''}
</div>`;

function replaceBetween(file, name, html) {
  const f = P(file);
  if (!fs.existsSync(f)) return;
  const s = fs.readFileSync(f, 'utf8');
  const a = `<!-- ${name}:START -->`, b = `<!-- ${name}:END -->`;
  const i = s.indexOf(a), j = s.indexOf(b);
  if (i < 0 || j < 0) return;
  fs.writeFileSync(f, s.slice(0, i + a.length) + '\n' + html + '\n        ' + s.slice(j));
}

function build() {
  fs.mkdirSync(P('blog'), { recursive: true });
  for (const dir of [P('blog')]) {                                // clear stale generated pages
    for (const f of fs.readdirSync(dir)) {
      const fp = path.join(dir, f);
      if (f.endsWith('.html') && fs.readFileSync(fp, 'utf8').includes(MARK)) fs.unlinkSync(fp);
    }
  }

  const posts = fs.readdirSync(P('posts')).filter(f => f.endsWith('.md')).map(parsePost)
    .filter(p => !p.draft).sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug));

  const postTpl = fs.readFileSync(P('templates', 'post.html'), 'utf8');
  const today = new Date().toISOString().slice(0, 10);

  posts.forEach((p, idx) => {
    const newer = posts[idx - 1], older = posts[idx + 1];
    const nav = [
      older ? `<a href="${older.slug}.html">← ${esc(older.title)}</a>` : '<span></span>',
      `<a href="index.html">All posts</a>`,
      newer ? `<a href="${newer.slug}.html">${esc(newer.title)} →</a>` : '<span></span>',
    ].join('');
    fs.writeFileSync(P('blog', `${p.slug}.html`), fill(postTpl, {
      title: esc(p.title), summary: esc(p.summary), date: fmtLong(p.date), minutes: p.minutes,
      content: p.html, nav, updated: today, mark: MARK,
      head: p.hasMath ? KATEX : '',
    }));
  });

  const item = (p, href) => `<li><span class="when">${fmtShort(p.date)}</span><span><a href="${href}">${esc(p.title)}</a>${p.summary ? `<br><small>${esc(p.summary)}</small>` : ''}</span></li>`;

  fs.writeFileSync(P('blog', 'index.html'), fill(fs.readFileSync(P('templates', 'blog-index.html'), 'utf8'), {
    mark: MARK, updated: today,
    list: posts.length ? `<ul class="dated">\n${posts.map(p => item(p, `${p.slug}.html`)).join('\n')}\n</ul>` : '<p>No posts yet.</p>',
  }));

  // data-driven pages
  replaceBetween('projects.html', 'PROJECTS', readJSON('data/projects.json', []).map(entryHTML).join('\n'));
  replaceBetween('papers.html', 'PAPERS', readJSON('data/papers.json', []).map(s =>
    `<section>\n  <h2 class="section-title">${esc(s.section)}</h2>\n${(s.items || []).map(entryHTML).join('\n')}\n</section>`).join('\n'));

  const newsItem = p => `<li><span class="when">${fmtShort(p.date)}</span><span><a href="blog/${p.slug}.html">${esc(p.title)}</a>${p.summary ? ` <span class="org">· ${esc(p.summary)}</span>` : ''}</span></li>`;
  replaceBetween('index.html', 'NEWS', `<ul class="dated">\n${posts.slice(0, 8).map(newsItem).join('\n')}\n<li><span class="when"></span><span><a href="blog/index.html">All posts →</a></span></li>\n</ul>`);
  seoPass(posts);
  console.log(`built ${posts.length} post${posts.length === 1 ? '' : 's'}: ${posts.map(p => p.slug).join(', ')}`);
}


/* ------------------------------ SEO, sitemap, feed ------------------------------ */

const escAttr = s => esc(String(s)).replace(/"/g, '&quot;');
const SEO_RE = /<!-- SEO:START -->[\s\S]*?<!-- SEO:END -->\n?/;

function htmlFiles() {
  const out = [];
  for (const f of fs.readdirSync(ROOT)) if (f.endsWith('.html')) out.push(f);
  for (const d of ['blog']) if (fs.existsSync(P(d))) for (const f of fs.readdirSync(P(d))) if (f.endsWith('.html')) out.push(`${d}/${f}`);
  return out;
}

// Adds canonical + Open Graph + Twitter tags + description to every page, stamps the footer date,
// and writes sitemap.xml, feed.xml and robots.txt. Configure in data/site.json.
function seoPass(posts) {
  const site = readJSON('data/site.json', {});
  const base = (site.url || '').replace(/\/$/, '');
  const today = new Date().toISOString().slice(0, 10);
  const pages = [];

  for (const rel of htmlFiles()) {
    let html = fs.readFileSync(P(rel), 'utf8');
    if (!html.includes('</head>')) continue;
    html = html.replace(/Site last updated \d{4}-\d{2}-\d{2}/g, `Site last updated ${today}`);
    const stripped = html.replace(SEO_RE, '');
    const title = ((stripped.match(/<title>([\s\S]*?)<\/title>/) || [])[1] || site.title || '').trim();
    const hasDesc = /<meta name="description"/.test(stripped);
    const desc = ((stripped.match(/<meta name="description" content="([^"]*)"/) || [])[1]) || (site.descriptions && site.descriptions[rel]) || site.description || '';
    const is404 = rel === '404.html';
    const isPost = rel.startsWith('blog/') && rel !== 'blog/index.html';
    const url = base ? `${base}/${rel.replace(/(^|\/)index\.html$/, '$1')}` : '';
    const depth = rel.split('/').length - 1;
    const pre = is404 ? '/' : '../'.repeat(depth);
    const lines = ['<meta name="theme-color" content="#ffffff">',
      `<link rel="icon" type="image/png" sizes="32x32" href="${pre}favicon-32.png">`,
      `<link rel="apple-touch-icon" href="${pre}apple-touch-icon.png">`];
    if (!hasDesc && desc) lines.push(`<meta name="description" content="${escAttr(desc)}">`);
    if (is404) lines.push('<meta name="robots" content="noindex">');
    else {
      if (url) lines.push(`<link rel="canonical" href="${url}">`);
      lines.push(`<meta property="og:site_name" content="${escAttr(site.title || '')}">`,
        `<meta property="og:type" content="${isPost ? 'article' : 'website'}">`,
        `<meta property="og:title" content="${title.replace(/"/g, '&quot;')}">`,
        `<meta property="og:description" content="${escAttr(desc)}">`);
      if (url) lines.push(`<meta property="og:url" content="${url}">`);
      if (base) lines.push(`<meta property="og:image" content="${base}/photos/profile.jpg">`);
      lines.push('<meta name="twitter:card" content="summary">');
      lines.push(`<link rel="alternate" type="application/rss+xml" title="${escAttr(site.title || 'Feed')}" href="${base ? base + '/feed.xml' : '../'.repeat(depth) + 'feed.xml'}">`);
    }
    const block = `<!-- SEO:START -->\n  ${lines.join('\n  ')}\n  <!-- SEO:END -->\n`;
    html = stripped.replace('</head>', `  ${block}</head>`).replace(/Site last updated \d{4}-\d{2}-\d{2}/g, `Site last updated ${today}`);
    fs.writeFileSync(P(rel), html);
    if (!is404) pages.push({ rel, url });
  }

  if (!base) return;
  const xml = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const postBySlug = Object.fromEntries(posts.map(p => [`blog/${p.slug}.html`, p]));
  fs.writeFileSync(P('sitemap.xml'), '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
    pages.map(({ rel, url }) => {
      const p = postBySlug[rel];
      const lm = p && /^\d{4}-\d{2}-\d{2}$/.test(p.date) ? `<lastmod>${p.date}</lastmod>` : '';
      return `  <url><loc>${xml(url)}</loc>${lm}</url>`;
    }).join('\n') + '\n</urlset>\n');
  fs.writeFileSync(P('feed.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<rss version="2.0"><channel>\n<title>${xml(site.title || '')}</title>\n<link>${base}/blog/</link>\n<description>${xml(site.description || '')}</description>\n` +
    posts.map(p => `<item><title>${xml(p.title)}</title><link>${base}/blog/${p.slug}.html</link><guid>${base}/blog/${p.slug}.html</guid><pubDate>${new Date(p.date.length === 7 ? p.date + '-01' : p.date).toUTCString()}</pubDate><description>${xml(p.summary)}</description></item>`).join('\n') +
    '\n</channel></rss>\n');
  fs.writeFileSync(P('robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${base}/sitemap.xml\n`);
}

/* ------------------------------ CLI ------------------------------ */

const [cmd, ...rest] = process.argv.slice(2);
fs.mkdirSync(P('posts'), { recursive: true });

if (cmd === 'new') {
  const title = rest[0];
  if (!title) { console.error('usage: node build.mjs new "Post title"'); process.exit(1); }
  const date = new Date().toISOString().slice(0, 10);
  const file = P('posts', `${date}-${slugify(title)}.md`);
  if (fs.existsSync(file)) { console.error('already exists:', file); process.exit(1); }
  fs.writeFileSync(file, `---\ntitle: ${title}\ndate: ${date}\nsummary: \n---\n\nWrite here. Use ## for section headings.\n`);
  console.log('created', path.relative(ROOT, file));
  build();
} else if (cmd === 'add-place') {
  const [name, lat, lng, note, link] = rest;
  if (!name || isNaN(+lat) || isNaN(+lng)) { console.error('usage: node build.mjs add-place "Name, Region" <lat> <lng> "Description" [link]'); process.exit(1); }
  const data = readJSON('data/places.json', { places: [] });
  data.places.push({ name, lat: +lat, lng: +lng, note: note || '', ...(link ? { link } : {}) });
  writeJSON('data/places.json', data);
  console.log(`added "${name}" to data/places.json`);
} else if (cmd === '--watch') {
  build();
  let t;
  for (const d of ['posts', 'templates', 'data']) fs.watch(P(d), () => { clearTimeout(t); t = setTimeout(() => { try { build(); } catch (e) { console.error(e.message); } }, 150); });
  console.log('watching posts/, templates/ and data/ ...');
} else {
  build();
}
